create or replace function public.admin_analytics_summary(p_days integer default 30)
returns table (
  registrations bigint,
  active_users bigint,
  tasks_created bigint,
  tasks_completed bigint,
  tasks_cancelled bigint,
  disputes_opened bigint,
  reports_opened bigint,
  avg_report_response_hours numeric,
  completion_rate numeric,
  cancellation_rate numeric,
  dispute_rate numeric
)
language sql
security definer
set search_path = ''
as $$
  with period as (
    select now() - make_interval(days => greatest(7, least(p_days, 90))) as since_at
  ),
  task_totals as (
    select
      count(*) filter (where t.created_at >= period.since_at) as created,
      count(*) filter (where t.completion_confirmed_at >= period.since_at) as completed,
      count(*) filter (where t.status = 'Cancelled' and t.created_at >= period.since_at) as cancelled
    from public.tasks t cross join period
  ),
  activity_totals as (
    select
      (select count(*) from public.user_profiles p, period where p.created_at >= period.since_at) as registrations,
      (select count(*) from public.account_presence ap where ap.last_seen_at >= now() - interval '5 minutes') as active_users,
      (select count(*) from public.task_disputes d, period where d.created_at >= period.since_at) as disputes,
      (select count(*) from public.task_reports r, period where r.created_at >= period.since_at) as reports,
      (select avg(extract(epoch from (r.reviewed_at-r.created_at))/3600)
        from public.task_reports r, period
        where r.created_at >= period.since_at and r.reviewed_at is not null) as response_hours
  )
  select
    activity_totals.registrations,
    activity_totals.active_users,
    task_totals.created,
    task_totals.completed,
    task_totals.cancelled,
    activity_totals.disputes,
    activity_totals.reports,
    round(activity_totals.response_hours::numeric, 1),
    case when task_totals.created=0 then 0 else round(task_totals.completed::numeric*100/task_totals.created,1) end,
    case when task_totals.created=0 then 0 else round(task_totals.cancelled::numeric*100/task_totals.created,1) end,
    case when task_totals.created=0 then 0 else round(activity_totals.disputes::numeric*100/task_totals.created,1) end
  from task_totals cross join activity_totals;
$$;
revoke all on function public.admin_analytics_summary(integer) from public, anon, authenticated;
grant execute on function public.admin_analytics_summary(integer) to service_role;

create or replace function public.admin_analytics_categories(p_days integer default 30)
returns table (category text, tasks bigint, completed bigint, cancelled bigint)
language sql
security definer
set search_path = ''
as $$
  select t.category, count(*),
    count(*) filter (where t.completion_confirmed_at is not null),
    count(*) filter (where t.status = 'Cancelled')
  from public.tasks t
  where t.created_at >= now() - make_interval(days => greatest(7, least(p_days, 90)))
  group by t.category
  order by count(*) desc, t.category
  limit 12;
$$;
revoke all on function public.admin_analytics_categories(integer) from public, anon, authenticated;
grant execute on function public.admin_analytics_categories(integer) to service_role;
