create table if not exists public.staff_permissions (
  user_id bigint primary key references public.user_profiles(id) on delete cascade,
  can_view_users boolean not null default false,
  can_moderate_tasks boolean not null default false,
  can_review_reports boolean not null default false,
  can_resolve_disputes boolean not null default false,
  updated_by bigint references public.user_profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);
alter table public.staff_permissions enable row level security;
revoke all on public.staff_permissions from public, anon, authenticated;
grant all on public.staff_permissions to service_role;

create table if not exists public.suspension_appeals (
  id bigint generated by default as identity primary key,
  user_id bigint references public.user_profiles(id) on delete set null,
  claimant_email text not null,
  claimant_name text not null,
  reason text not null check (length(reason) between 20 and 2000),
  status varchar(20) not null default 'Open' check (status in ('Open','Approved','Denied')),
  resolution_note text,
  reviewed_by bigint references public.user_profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists suspension_appeals_one_open_per_user_idx
  on public.suspension_appeals(user_id) where status = 'Open' and user_id is not null;
create index if not exists suspension_appeals_created_idx
  on public.suspension_appeals(created_at desc, id desc);
alter table public.suspension_appeals enable row level security;
revoke all on public.suspension_appeals from public, anon, authenticated;
grant all on public.suspension_appeals to service_role;
grant usage, select on sequence public.suspension_appeals_id_seq to service_role;

create table if not exists public.platform_announcements (
  id bigint generated by default as identity primary key,
  created_by bigint references public.user_profiles(id) on delete set null,
  title varchar(120) not null,
  body varchar(2000) not null,
  audience varchar(20) not null default 'everyone' check (audience in ('everyone','members','staff')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (expires_at is null or expires_at > starts_at)
);
create index if not exists platform_announcements_active_idx
  on public.platform_announcements(is_published, starts_at desc, expires_at);
alter table public.platform_announcements enable row level security;
revoke all on public.platform_announcements from public, anon, authenticated;
grant all on public.platform_announcements to service_role;
grant usage, select on sequence public.platform_announcements_id_seq to service_role;

